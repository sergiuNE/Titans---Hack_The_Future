// Languages and texts. No React. Only readLang/storeLang touch localStorage; the rest is pure.
// The hook that holds the chosen language is components/LangProvider.tsx.
// Every new text goes into all three dictionaries: TypeScript errors when fr or en misses a key of nl.

export type Lang = 'nl' | 'fr' | 'en';

export const LANGS: Lang[] = ['nl', 'fr', 'en'];
export const LANG_NAMES: Record<Lang, string> = { nl: 'Nederlands', fr: 'Français', en: 'English' };
export const LOCALES: Record<Lang, string> = { nl: 'nl-BE', fr: 'fr-BE', en: 'en-GB' };

/** Per device, in this browser only: never synced and not part of the State. */
export const LANG_KEY = 'anker:lang';

export function parseLang(raw: string | null): Lang {
  return raw === 'fr' || raw === 'en' ? raw : 'nl';
}

export function readLang(): Lang {
  try {
    return parseLang(localStorage.getItem(LANG_KEY));
  } catch {
    return 'nl';
  }
}

export function storeLang(lang: Lang) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // The language still applies until the page reloads.
  }
}

